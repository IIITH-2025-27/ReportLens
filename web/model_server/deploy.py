"""Publish the models to the ReportLens Hugging Face org and (re)deploy the model server Space.

    python web/model_server/deploy.py              (from the repository root; uses your `hf auth login` token)

1. Uploads checkpoints/lora_chart2table to a private model repo (ReportLens/qwen3-vl-4b-chart2table-lora).
   Qwen3-VL-4B and DePlot are public on the Hub, so the Space loads them from their own repos.
2. Builds the Space folder: app.py, Dockerfile, requirements.txt, a Space card, and the parts of
   chart_claim_verifier the server imports (copied, so the repo stays the single source of the model code).
3. Uploads it to a private Docker Space (<owner>/model-server) on free CPU hardware. Hugging Face only allows
   free Docker Spaces in an organization on a paid plan, so pass --space-owner <your username> otherwise.

The script does not copy any token into the Space. Add a read-only token as the Space secret HF_TOKEN once, in
the Space settings, so it can download the private adapter.

Run it again after changing the model code; only changed files are uploaded.
"""
from __future__ import annotations

import argparse
import json
import shutil
import tempfile
from pathlib import Path

from huggingface_hub import HfApi, get_token

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
ORG = "ReportLens"
MODEL_REPO = f"{ORG}/qwen3-vl-4b-chart2table-lora"
SPACE_NAME = "model-server"
ADAPTER_DIR = ROOT / "checkpoints" / "lora_chart2table"
PACKAGE_PARTS = ["__init__.py", "schemas.py", "models", "tools"]      # what app.py imports, with their imports

SPACE_CARD = """---
title: ReportLens model server
sdk: docker
app_port: 7860
pinned: false
short_description: Qwen3-VL-4B with a chart-to-table LoRA, and DePlot
---

Model server for the ReportLens chart claim verifier. It runs Qwen3-VL-4B-Instruct with the chart-to-table
LoRA adapter ([{model}](https://huggingface.co/{model})) and google/deplot behind a job API. The client is
`chart_claim_verifier/models/remote.py`; set `models.remote_url` to this Space's URL.

`GET /health` shows whether the models are loaded. The files here are generated by
`web/model_server/deploy.py` in the project repository; change them there.
""".format(model=MODEL_REPO)


def model_card() -> str:
    s = json.loads((ADAPTER_DIR / "summary.json").read_text())
    cfg = json.loads((ADAPTER_DIR / "adapter_config.json").read_text())
    return f"""---
base_model: Qwen/Qwen3-VL-4B-Instruct
library_name: peft
pipeline_tag: image-text-to-text
tags:
- lora
- chart-to-table
---

# Qwen3-VL-4B chart-to-table LoRA (ReportLens)

A LoRA adapter for [Qwen/Qwen3-VL-4B-Instruct](https://huggingface.co/Qwen/Qwen3-VL-4B-Instruct) that turns a
chart image into its data table. It is the `vlm_table` tool of the ReportLens chart claim verifier, which
checks the numbers written in a report against the report's own charts. The verifier's other uses of the model
(reading one point, legend names, claim parsing) run with the adapter switched off.

## Training

- Data: {s['charts']} synthetic charts with known values, rendered by the project's chart generator
- {s['epochs']:g} epoch, {s['steps']} steps, {s['minutes']:.0f} minutes; validation loss after training {s['val_loss_after']:.3f}
- LoRA rank {cfg['r']}, alpha {cfg['lora_alpha']}, dropout {cfg['lora_dropout']}, on the language model's
  attention and MLP projections; trained in bfloat16 on Apple silicon (`scripts/finetune/finetune_lora.py`)
- `train_log.jsonl` has the loss per step

## Effect

On the verifier's 51 calibration charts (1,063 readings), compared with the base model:

| | base | with LoRA |
|---|---|---|
| answers given | 66.2% | 74.0% |
| median error (% of the axis range) | 1.4 | 0.8 |
| 90th-percentile error (% of the axis range) | 17.3 | 8.7 |
| badly wrong (more than 5% of the axis range off) | 26.0% | 17.3% |

## Use

```python
from peft import PeftModel
from transformers import AutoModelForImageTextToText, AutoProcessor

base = AutoModelForImageTextToText.from_pretrained("Qwen/Qwen3-VL-4B-Instruct", dtype="float16")
model = PeftModel.from_pretrained(base, "{MODEL_REPO}")
```

The verifier's calibration table for this adapter (`calibration_tables/local_lora`) was measured with
float16 inference on Apple silicon. On other hardware, re-read the calibration charts before trusting the margins.
"""


def build_space(dst: Path) -> None:
    for name in ("app.py", "Dockerfile", "requirements.txt"):
        shutil.copy(HERE / name, dst / name)
    (dst / "README.md").write_text(SPACE_CARD)
    pkg = dst / "chart_claim_verifier"
    pkg.mkdir()
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc")
    for part in PACKAGE_PARTS:
        src = ROOT / "chart_claim_verifier" / part
        (shutil.copytree(src, pkg / part, ignore=ignore) if src.is_dir() else shutil.copy(src, pkg / part))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--skip-model", action="store_true", help="do not upload the adapter again")
    ap.add_argument("--hardware", default="cpu-basic", help="cpu-basic is free; t4-small is a paid GPU")
    ap.add_argument("--space-owner", default=ORG,
                    help="account or org for the Space; free Docker Spaces need a personal account or a paid org plan")
    args = ap.parse_args()
    token = get_token()
    if not token:
        raise SystemExit("Log in first: hf auth login")
    api = HfApi(token=token)

    if not args.skip_model:
        api.create_repo(MODEL_REPO, repo_type="model", private=True, exist_ok=True)
        with tempfile.TemporaryDirectory() as tmp:
            for f in ("adapter_config.json", "adapter_model.safetensors", "summary.json", "train_log.jsonl"):
                shutil.copy(ADAPTER_DIR / f, Path(tmp) / f)
            (Path(tmp) / "README.md").write_text(model_card())
            api.upload_folder(repo_id=MODEL_REPO, folder_path=tmp, commit_message="Upload chart-to-table LoRA")
        print("model:", f"https://huggingface.co/{MODEL_REPO}")

    SPACE_REPO = f"{args.space_owner}/{SPACE_NAME}"
    api.create_repo(SPACE_REPO, repo_type="space", space_sdk="docker", private=True, exist_ok=True,
                    space_hardware=args.hardware)
    api.add_space_variable(SPACE_REPO, "LORA_REPO", MODEL_REPO)
    with tempfile.TemporaryDirectory() as tmp:
        build_space(Path(tmp))
        api.upload_folder(repo_id=SPACE_REPO, repo_type="space", folder_path=tmp,
                          commit_message="Deploy model server", delete_patterns=["*.py", "**/*.py"])
    host = SPACE_REPO.lower().replace("/", "-")
    print("space:", f"https://huggingface.co/spaces/{SPACE_REPO}")
    print("remote_url:", f"https://{host}.hf.space")
    print(f"The Space needs a token to download the private adapter: in the Space settings add a secret named "
          f"HF_TOKEN holding a read-only token (https://huggingface.co/settings/tokens) with access to {MODEL_REPO}.")


if __name__ == "__main__":
    main()
