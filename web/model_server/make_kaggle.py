"""Build a Kaggle notebook that runs the model server on Kaggle's free T4 GPU.

    python web/model_server/make_kaggle.py        (from the repository root)

Writes web/model_server/kaggle_server.ipynb. The notebook carries the server (app.py) and the parts of
chart_claim_verifier it imports, packed inside it, so nothing has to be cloned or attached on Kaggle.
Build it again after changing the model code.

On Kaggle: create a notebook, File > Import notebook, pick the file; Settings: Accelerator GPU T4, Internet on;
Add-ons > Secrets: HF_TOKEN (a read-only token that can read the ReportLens org); then Run all. The last cell
prints the two lines for web/backend/.env and keeps the server running until you stop it.
"""
from __future__ import annotations

import base64
import io
import json
import tarfile
import tempfile
from pathlib import Path

from deploy import HERE, MODEL_REPO, build_space

OUT = HERE / "kaggle_server.ipynb"

# Kaggle already has torch, torchvision, pillow, numpy and pydantic; these pin what the server was tested with
PIP = "transformers==5.5.4 peft==0.21.2 accelerate rapidfuzz fastapi uvicorn"


def bundle() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        build_space(Path(tmp))
        buf = io.BytesIO()
        with tarfile.open(fileobj=buf, mode="w:gz") as tar:
            for name in ("app.py", "chart_claim_verifier"):
                tar.add(Path(tmp) / name, arcname=name)
    return base64.b64encode(buf.getvalue()).decode()


