def notebook(packed: str) -> dict:
    out = []
    for kind, src in cells():
        cell = {"cell_type": kind, "metadata": {}, "source": src.splitlines(keepends=True)}
        if kind == "code":
            cell.update(execution_count=None, outputs=[])
        out.append(cell)
    # the packed code goes in its own cell first, so the readable cells stay short
    out.insert(1, {"cell_type": "code", "metadata": {"jupyter": {"source_hidden": True}}, "execution_count": None,
                   "outputs": [], "source": [f'PACKED = "{packed}"  # app.py + chart_claim_verifier parts, tar.gz\n']})
    return {"cells": out, "nbformat": 4, "nbformat_minor": 5,
            "metadata": {"kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"},
                         "language_info": {"name": "python"},
                         "kaggle": {"accelerator": "nvidiaTeslaT4", "isInternetEnabled": True,
                                    "isGpuEnabled": True}}}


def main() -> None:
    packed = bundle()
    OUT.write_text(json.dumps(notebook(packed), indent=1))
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
